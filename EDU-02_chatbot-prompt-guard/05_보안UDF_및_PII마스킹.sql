--      전혀 마스킹되지 않았다.** 이메일만 마스킹되었다.
--      그런데 단위 테스트는 하이픈만 있는 문자열을 쓰므로 **통과했다.**
--      → 단위 테스트 통과가 방어 성공을 뜻하지 않는 조용한 실패였다.
--      정정: 각 구분자에 \\s* 를 넣고, \\b 를 제거했다.
--
--   ✅ MASK_PII_TEXT 생성 — 실제 실행 검증 완료
