-- DROP FUNCTION IF EXISTS KSM_CHATBOT_DB.SECURITY.MASK_PII_TEXT(VARCHAR);
-- DROP FUNCTION IF EXISTS KSM_CHATBOT_DB.SECURITY.CALCULATE_STAGE_FILE_HASH(STRING);
