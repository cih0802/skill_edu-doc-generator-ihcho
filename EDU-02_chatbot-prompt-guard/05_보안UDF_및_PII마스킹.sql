-- ##############################################################################
-- [1] PII 마스킹 SQL UDF
-- ##############################################################################
-- 문서 텍스트를 벡터 인덱싱하기 **전에** 개인정보를 치환합니다.
-- 저장소(DOCUMENT_CHUNKS)와 검색 인덱스에 원본 PII가 들어가지 않게 하는 것이 목적입니다.
--
-- 🔴 이 UDF의 한계를 반드시 인지하십시오. 정규식은 아래를 잡지 못합니다.
--    · 형식이 어긋난 표기 (예: 공백·점으로 구분된 번호, 전각 숫자)
--    · 이름·주소·계좌번호·여권번호 등 패턴이 정형화되지 않은 식별정보
--    · OCR 오인식으로 숫자가 깨진 경우
--    따라서 이것은 **완전한 비식별 조치가 아니며**, 실제 개인정보가 든 문서를
--    이 실습에 투입하면 안 됩니다.
-- IF NOT EXISTS: 재실행 시 기존 함수를 덮어쓰지 않습니다.
--    본문을 수정해 다시 배포해야 하면 CREATE OR REPLACE 로 바꾸십시오
--    (함수는 상태를 갖지 않으므로 교체로 잃는 데이터가 없습니다).

CREATE FUNCTION IF NOT EXISTS KSM_CHATBOT_DB.SECURITY.MASK_PII_TEXT(RAW_TEXT VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
IMMUTABLE
COMMENT = '주민번호/휴대전화/이메일 정규식 마스킹. 완전한 비식별 조치가 아님. [chatbot-prompt-guard]'
AS
$$
    -- 1) 주민등록번호  900101-1234567 → 900101-*******
    -- 2) 휴대전화번호  010-1234-5678  → 010-****-5678
    -- 3) 이메일 주소   a@b.com        → [EMAIL_MASKED]
    --
    -- 🔴🔴 \\s* 가 왜 필요한가 — 실습 완주로 발견된 결함 🔴🔴
    --   AI_PARSE_DOCUMENT 는 PDF 에서 텍스트를 뽑을 때 **하이픈 뒤에 공백을
    --   삽입할 수 있습니다.** 2026-09-17 계정 LJ20513 실측:
    --     PDF 원문       : 010-9876-5432      / 950505-1234567
    --     파싱 결과      : 010- 9876- 5432    / 950505- 1234567
    --   이전 판의 정규식은 하이픈 앞뒤 공백을 허용하지 않아 **파싱된 실제
    --   텍스트에서 전화번호와 주민번호가 전혀 마스킹되지 않았습니다.**
    --   그런데 [3] 의 단위 테스트는 하이픈만 있는 문자열을 쓰므로 **통과했습니다.**
    --   → 단위 테스트만 보면 방어가 되는 것처럼 보이는 조용한 실패였습니다.
    --   그래서 각 구분자에 \\s* 를 넣었습니다. [3] 에 파싱 형태 테스트도 추가했습니다.
    --
    -- ⚠️ 트레이드오프(실측): 주민번호 패턴의 하이픈을 선택(-?)으로 두면
    --   '9505051234567'(하이픈 없음), '950505 1234567'(공백 구분)까지 잡지만,
    --   17자리 문서번호 '20260917123456789' 를 '202609-*******6789' 로
    --   **과잉 마스킹**합니다. 보안 목적에서는 누락보다 과잉이 안전하므로
    --   이 자료는 -? 를 유지합니다. 오탐이 문제가 되는 환경이라면
    --   '\\s*-\\s*' 로 하이픈을 필수화하십시오(대신 위 두 형태를 놓칩니다).
    --   날짜(2026-09-17), 금액(2000000), 사업자번호(123-45-67890)는
    --   두 방식 모두에서 오탐이 없음을 확인했습니다.
    SELECT
        REGEXP_REPLACE(
            REGEXP_REPLACE(
                REGEXP_REPLACE(
                    RAW_TEXT,
                    '([0-9]{6})\\s*-?\\s*([1-8][0-9]{6})',
                    '\\1-*******'
                ),
                '(01[016789])\\s*-?\\s*([0-9]{3,4})\\s*-?\\s*([0-9]{4})',
                '\\1-****-\\3'
            ),
            '[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\\.[A-Za-z]{2,}',
            '[EMAIL_MASKED]'
        )
$$;


-- ##############################################################################
-- [2] 스테이지 파일 해시 계산 Python UDF (보조)
-- ##############################################################################
-- 디렉터리 테이블의 MD5 컬럼으로도 변경 감지가 가능하므로 06_ 의 파이프라인은
-- 이 UDF를 사용하지 않습니다. 파일 무결성을 별도로 확인하고 싶을 때 쓰는 보조 함수입니다.
-- SnowflakeFile.open 에 넘기는 URL 은 BUILD_STAGE_FILE_URL 로 만든 스코프 URL 입니다.

CREATE FUNCTION IF NOT EXISTS KSM_CHATBOT_DB.SECURITY.CALCULATE_STAGE_FILE_HASH(FILE_URL STRING)
RETURNS STRING
LANGUAGE PYTHON
RUNTIME_VERSION = '3.11'
PACKAGES = ('snowflake-snowpark-python')
HANDLER = 'calculate_hash'
COMMENT = '스테이지 파일의 바이너리 MD5 해시 계산(변경 감지 용도). [chatbot-prompt-guard]'
AS
$$
import hashlib
from snowflake.snowpark.files import SnowflakeFile

def calculate_hash(file_url: str) -> str:
    if not file_url:
        return None
    try:
        hasher = hashlib.md5()
        with SnowflakeFile.open(file_url, 'rb') as f:
            while True:
                chunk = f.read(8192)
                if not chunk:
                    break
                hasher.update(chunk)
        return hasher.hexdigest()
    except Exception as e:
        # 🔴 조용한 실패(silent failure) 주의 — 이 패턴은 결함에 가깝습니다.
        #    예외를 삼켜 'ERROR: ...' 라는 **정상 문자열**로 반환하므로,
        #    호출부는 SQL 오류를 보지 못하고 그 값을 해시로 착각해 저장할 수 있습니다.
        #    함수는 "성공"했고 컬럼에는 값이 들어가므로 아무도 알아채지 못합니다.
        #
        #    운영에서는 아래 중 하나를 반드시 하십시오.
        #      ① 예외를 그대로 올린다 (raise) → 호출 쿼리가 실패해 즉시 드러난다
        #      ② 값 대신 NULL 을 반환하고, 실패를 별도 감사 테이블/알림에 남긴다
        #    여기서는 학습용으로 오류 메시지를 노출하지만,
        #    **호출부에서 반환값이 'ERROR:' 로 시작하는지 반드시 검사해야 합니다.**
        #    예: WHERE FILE_HASH NOT LIKE 'ERROR:%'
        return f"ERROR: {str(e)}"
$$;


-- ##############################################################################
-- [3] 마스킹 테스트 — 🔴 단위 테스트만 하지 마십시오
-- ##############################################################################
-- 🔴 이 절의 구성이 바뀐 이유:
--    이전 판은 3.0 단위 테스트 하나만 두었고, 그 입력은 하이픈이 붙은
--    '010-9876-5432' 였습니다. 그래서 통과했습니다.
--    그러나 실습이 실제로 마스킹해야 하는 대상은 AI_PARSE_DOCUMENT 가
--    PDF 에서 뽑아낸 텍스트이고, 그 형태는 '010- 9876- 5432' 였습니다.
--    **단위 테스트는 통과하는데 실제 파이프라인에서는 마스킹이 실패**했습니다.
--    따라서 아래 3.1 (파싱 실제 형태) 테스트를 반드시 함께 실행하십시오.

-- 3.0 단위 테스트 (하이픈 형태)
-- 기대 출력: '담당자: 홍길동 (010-****-5432, 950505-*******, [EMAIL_MASKED])'
SELECT
    '담당자: 홍길동 (010-9876-5432, 950505-1234567, contact@ksm.co.kr)' AS ORIGINAL_TEXT,
    KSM_CHATBOT_DB.SECURITY.MASK_PII_TEXT(ORIGINAL_TEXT)               AS SANITIZED_TEXT;

-- 3.1 🔴 파싱 실제 형태 테스트 — 하이픈 뒤 공백이 삽입된 경우
--     이것이 06_ 파이프라인이 실제로 받는 입력 형태입니다.
--     2026-09-17 실행 관찰: 세 형태 모두 마스킹됨
SELECT
    '담당자 김보안 010- 9876- 5432, 이메일 security@ksm.co.kr 로 연락한다.' AS PARSED_FORM_1,
    KSM_CHATBOT_DB.SECURITY.MASK_PII_TEXT(PARSED_FORM_1)                    AS MASKED_1;

SELECT
    '주민등록번호 950505- 1234567 같은 고유식별정보는 암호화 보관한다.'      AS PARSED_FORM_2,
    KSM_CHATBOT_DB.SECURITY.MASK_PII_TEXT(PARSED_FORM_2)                    AS MASKED_2;
--   관찰 결과 — 전화번호 마스킹됨? ______   주민번호 마스킹됨? ______
--   🔴 하나라도 마스킹되지 않으면 06_ 로 진행하지 마십시오.

-- 3.2 한계 확인 테스트 — 정규식이 처리하지 **못하는** 것을 직접 보십시오
SELECT
    '연락처 010 1234 5678 / 홍길동 / 서울시 강남구 / 110-123-456789' AS EDGE_CASE_INPUT,
    KSM_CHATBOT_DB.SECURITY.MASK_PII_TEXT(EDGE_CASE_INPUT)             AS EDGE_CASE_OUTPUT;
--   2026-09-17 실행 관찰:
--     · '010 1234 5678' (공백 구분) → 010-****-5678 로 **마스킹됩니다**
--       (\\s* 를 넣은 결과. 이전 판에서는 마스킹되지 않았습니다)
--     · '홍길동'(이름), '서울시 강남구'(주소), '110-123-456789'(계좌번호)
--       → **마스킹되지 않습니다.** 이 UDF의 범위 밖입니다
--   관찰 결과: ______________________________________________
--
--   🔴 따라서 이 UDF는 완전한 비식별 조치가 아닙니다. 이름·주소·계좌번호가
--      포함된 문서를 인덱싱한다면 별도 대책이 필요합니다.

-- 3.3 오탐(false positive) 확인 — 마스킹되면 안 되는 것들
SELECT
    '기간 2026-09-17 / 교육비 2000000 원 / 사업자번호 123-45-67890' AS FP_INPUT,
    KSM_CHATBOT_DB.SECURITY.MASK_PII_TEXT(FP_INPUT)                   AS FP_OUTPUT;
--   2026-09-17 실행 관찰: 날짜·금액·사업자번호 모두 마스킹되지 않음(정상)
--   관찰 결과: ______________________________________________
--   ⚠️ 단, 17자리 이상 연속 숫자(예: 문서번호 20260917123456789)는
--      주민번호 패턴에 걸려 과잉 마스킹될 수 있습니다(상단 트레이드오프 주석 참고).

-- 3.4 함수 생성 확인
